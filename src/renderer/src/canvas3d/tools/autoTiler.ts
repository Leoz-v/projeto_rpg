/**
 * Lost-City / RS2 smooth vertex-contour auto-tiler + WorldLab continuous-mask fitter.
 *
 * Compared against Lost City's Client-TS Ground.ts and authentic 2004 RS2 maps
 * (Lumbridge m50_50, Draynor m49_50, Varrock m50_53):
 *   - Uses a 5x5 separable binomial-smoothed vertex contour field ([1,4,6,4,1]/16)
 *     around authored AUTO_SEED tiles so painted terrain naturally produces the real
 *     RS2 shape vocabulary:
 *       · Straight edges       -> Full (1) / Half (3)
 *       · Outside/inside turns -> Corner Small (4) / Corner Big (5) / Fan Small (11) / Fan Big (12)
 *       · 1-tile diagonal path -> Diagonal (2) + Full (1)
 *       · 2:1 & 1:2 slopes     -> paired Left/Right Semi-Diag Big & Small (7, 8, 9, 10)
 *   - Excludes Trapezoid (6) from auto-tiling (0 occurrences across Lumbridge, Draynor,
 *     and Varrock) to avoid sawtooth notches and 3D slope height kinks.
 *   - Overlap-guarded 8-pass shared-edge harmonizer with Empty (0) fringe fallback
 *     prevents backwards/disconnected triangles and eliminates shared-edge mismatches.
 *   - Preserves WorldLab's reversible mixed-material transition substrates
 *     (AUTO_UNDERLAY_OVERRIDE) and MANUAL_LOCK protection.
 */

import { getMaterial } from '../terrain/materials';
import {
  TILE_AUTO_GENERATED,
  TILE_AUTO_SEED,
  TILE_AUTO_UNDERLAY_OVERRIDE,
  TILE_MANUAL_LOCK,
  type TerrainGrid,
  type TileData,
} from '../terrain/terrainGrid';
import {
  OVERLAY_SHAPE_FULL,
  TOPOLOGY_PROBES,
  fitTopology,
  harmonizeShapes,
  parseTileCoordKey,
  sampleMaskProbes,
  tileCoordKey,
  type ShapeFit,
} from './shapeFitter';

const AUTO_SPILL_COST = 1.35;
const CONTOUR_ISO = 0.4999;
const SCORE_EPSILON = 1e-9;
/** 2-pass 3x3 binomial kernel [1,2,1]/4 convolved with itself -> exact 5-tap separable kernel. */
const BINOMIAL_K5: readonly number[] = [1 / 16, 4 / 16, 6 / 16, 4 / 16, 1 / 16];

interface Seed {
  readonly x: number;
  readonly z: number;
  readonly material: number;
}

interface TransitionTarget {
  readonly representable: boolean;
  readonly underlayId: number;
}

export interface AutoTilePlacement {
  readonly material: number;
  readonly shape: number;
  readonly rotation: number;
  readonly seed: boolean;
  readonly underlayOverride: number;
}

export function isManualLocked(meta: number): boolean {
  return (meta & TILE_MANUAL_LOCK) !== 0;
}

export function isAutoSeed(meta: number): boolean {
  return (meta & TILE_AUTO_SEED) !== 0;
}

export function isAutoGenerated(meta: number): boolean {
  return (meta & TILE_AUTO_GENERATED) !== 0;
}

export function lockManualMetadata(meta: number): number {
  return (meta & ~(TILE_AUTO_SEED | TILE_AUTO_GENERATED | TILE_AUTO_UNDERLAY_OVERRIDE)) | TILE_MANUAL_LOCK;
}

function resolveTransitionTarget(overlayId: number): TransitionTarget {
  if (overlayId === 0) return { representable: true, underlayId: 0 };
  const mat = getMaterial(overlayId);
  const sub = mat.transitionUnderlayId;
  if (sub <= 0) return { representable: false, underlayId: 0 };
  return { representable: true, underlayId: sub };
}

function spatiallyBefore(a: Seed, b: Seed): boolean {
  if (a.z !== b.z) return a.z < b.z;
  return a.x < b.x;
}

function rawVertexDensity(vx: number, vz: number, material: number, seedAt: (sx: number, sz: number) => number): number {
  let c = 0;
  if (seedAt(vx - 1, vz - 1) === material) c++;
  if (seedAt(vx, vz - 1) === material) c++;
  if (seedAt(vx - 1, vz) === material) c++;
  if (seedAt(vx, vz) === material) c++;
  return c * 0.25;
}

function smoothVertexDensity(
  vx: number,
  vz: number,
  material: number,
  seedAt: (sx: number, sz: number) => number
): number {
  let sum = 0;
  for (let dz = -2; dz <= 2; dz++) {
    const wz = BINOMIAL_K5[dz + 2]!;
    for (let dx = -2; dx <= 2; dx++) {
      sum += rawVertexDensity(vx + dx, vz + dz, material, seedAt) * wz * BINOMIAL_K5[dx + 2]!;
    }
  }
  return sum;
}

function isIn2x2Block(tx: number, tz: number, material: number, seedAt: (sx: number, sz: number) => number): boolean {
  if (seedAt(tx, tz) !== material) return false;
  const b0 = seedAt(tx - 1, tz - 1) === material && seedAt(tx, tz - 1) === material && seedAt(tx - 1, tz) === material;
  const b1 = seedAt(tx + 1, tz - 1) === material && seedAt(tx, tz - 1) === material && seedAt(tx + 1, tz) === material;
  const b2 = seedAt(tx - 1, tz + 1) === material && seedAt(tx, tz + 1) === material && seedAt(tx - 1, tz) === material;
  const b3 = seedAt(tx + 1, tz + 1) === material && seedAt(tx, tz + 1) === material && seedAt(tx + 1, tz) === material;
  return b0 || b1 || b2 || b3;
}

/**
 * True only for genuinely thin 1-tile features (single-tile clicks, 1-tile straight roads,
 * 1-tile diagonal paths) — never for corner overhang tips of a wider 2+ tile region.
 */
function isThinSeedTile(tx: number, tz: number, material: number, seedAt: (sx: number, sz: number) => number): boolean {
  if (seedAt(tx, tz) !== material) return false;
  if (isIn2x2Block(tx, tz, material, seedAt)) return false;
  if (isIn2x2Block(tx - 1, tz, material, seedAt)) return false;
  if (isIn2x2Block(tx + 1, tz, material, seedAt)) return false;
  if (isIn2x2Block(tx, tz - 1, material, seedAt)) return false;
  if (isIn2x2Block(tx, tz + 1, material, seedAt)) return false;
  return true;
}

/**
 * Checks if a non-seed tile sits in the concave crook between two orthogonally adjacent
 * thin seeds of the same material (a 1-tile diagonal staircase step -> crisp RS2 Diagonal!).
 */
function resolveThinDiagonalBridge(
  tx: number,
  tz: number,
  seedAt: (sx: number, sz: number) => number
): { material: number; target: boolean[] } | null {
  if (seedAt(tx, tz) !== 0) return null;
  const s = seedAt(tx, tz - 1);
  const n = seedAt(tx, tz + 1);
  const w = seedAt(tx - 1, tz);
  const e = seedAt(tx + 1, tz);

  if (s !== 0 && s === e && n !== s && w !== s && isThinSeedTile(tx, tz - 1, s, seedAt) && isThinSeedTile(tx + 1, tz, s, seedAt)) {
    return { material: s, target: TOPOLOGY_PROBES.map((p) => p.u >= p.v) };
  }
  if (s !== 0 && s === w && n !== s && e !== s && isThinSeedTile(tx, tz - 1, s, seedAt) && isThinSeedTile(tx - 1, tz, s, seedAt)) {
    return { material: s, target: TOPOLOGY_PROBES.map((p) => p.u + p.v <= 1) };
  }
  if (n !== 0 && n === e && s !== n && w !== n && isThinSeedTile(tx, tz + 1, n, seedAt) && isThinSeedTile(tx + 1, tz, n, seedAt)) {
    return { material: n, target: TOPOLOGY_PROBES.map((p) => p.u + p.v >= 1) };
  }
  if (n !== 0 && n === w && s !== n && e !== n && isThinSeedTile(tx, tz + 1, n, seedAt) && isThinSeedTile(tx - 1, tz, n, seedAt)) {
    return { material: n, target: TOPOLOGY_PROBES.map((p) => p.v >= p.u) };
  }
  return null;
}

interface TileMaterialField {
  readonly material: number;
  readonly sw: number;
  readonly se: number;
  readonly nw: number;
  readonly ne: number;
  readonly nearestSeed: Seed;
  readonly nearestDistSq: number;
}

function sampleField(f: TileMaterialField, u: number, v: number): number {
  return (f.sw * (1 - u) + f.se * u) * (1 - v) + (f.nw * (1 - u) + f.ne * u) * v;
}

function buildTileFields(
  tx: number,
  tz: number,
  nearby: readonly Seed[],
  seedAt: (sx: number, sz: number) => number
): TileMaterialField[] {
  const byMat = new Map<number, { seed: Seed; distSq: number }>();
  const cx = tx + 0.5;
  const cz = tz + 0.5;
  for (const s of nearby) {
    const dx = cx - (s.x + 0.5);
    const dz = cz - (s.z + 0.5);
    const distSq = dx * dx + dz * dz;
    const prev = byMat.get(s.material);
    if (
      !prev ||
      distSq < prev.distSq - SCORE_EPSILON ||
      (Math.abs(distSq - prev.distSq) <= SCORE_EPSILON && spatiallyBefore(s, prev.seed))
    ) {
      byMat.set(s.material, { seed: s, distSq });
    }
  }

  const fields: TileMaterialField[] = [];
  for (const [mat, nearest] of byMat) {
    fields.push({
      material: mat,
      sw: smoothVertexDensity(tx, tz, mat, seedAt),
      se: smoothVertexDensity(tx + 1, tz, mat, seedAt),
      nw: smoothVertexDensity(tx, tz + 1, mat, seedAt),
      ne: smoothVertexDensity(tx + 1, tz + 1, mat, seedAt),
      nearestSeed: nearest.seed,
      nearestDistSq: nearest.distSq,
    });
  }
  return fields;
}

function ownerAtProbe(u: number, v: number, fields: readonly TileMaterialField[]): number {
  let best: TileMaterialField | null = null;
  let bestVal = CONTOUR_ISO;

  for (const f of fields) {
    const val = sampleField(f, u, v);
    if (val < CONTOUR_ISO) continue;
    if (
      !best ||
      val > bestVal + SCORE_EPSILON ||
      (Math.abs(val - bestVal) <= SCORE_EPSILON &&
        (f.nearestDistSq < best.nearestDistSq - SCORE_EPSILON ||
          (Math.abs(f.nearestDistSq - best.nearestDistSq) <= SCORE_EPSILON &&
            spatiallyBefore(f.nearestSeed, best.nearestSeed))))
    ) {
      best = f;
      bestVal = val;
    }
  }
  return best ? best.material : 0;
}

function pickDominantFromWeights(
  x: number,
  z: number,
  weights: ReadonlyMap<number, number>,
  seeds: readonly Seed[]
): number {
  if (weights.size === 0) return 0;
  let bestWeight = -1;
  for (const w of weights.values()) {
    if (w > bestWeight) bestWeight = w;
  }
  const tied = new Set<number>();
  for (const [mat, w] of weights) {
    if (w === bestWeight) tied.add(mat);
  }
  if (tied.size === 1) {
    return tied.values().next().value ?? 0;
  }

  let best: Seed | null = null;
  let bestDist = Infinity;
  const cx = x + 0.5;
  const cz = z + 0.5;
  for (const seed of seeds) {
    if (!tied.has(seed.material)) continue;
    const dx = cx - (seed.x + 0.5);
    const dz = cz - (seed.z + 0.5);
    const dist = dx * dx + dz * dz;
    if (
      !best ||
      dist < bestDist - SCORE_EPSILON ||
      (Math.abs(dist - bestDist) <= SCORE_EPSILON && spatiallyBefore(seed, best))
    ) {
      best = seed;
      bestDist = dist;
    }
  }
  return best ? best.material : 0;
}

function solveTileFromSeeds(
  x: number,
  z: number,
  seedAt: (sx: number, sz: number) => number
): { placement: AutoTilePlacement; target: boolean[]; lockFullThin: boolean } {
  const own = seedAt(x, z);
  const authoredSeed = own !== 0;

  // Check immediate 3x3 ring for nearby seeds (no overlay spawns beyond 1 tile of an authored seed)
  let hasImmediateNeighborSeed = authoredSeed;
  const nearby: Seed[] = [];
  for (let sx = x - 3; sx <= x + 3; sx++) {
    for (let sz = z - 3; sz <= z + 3; sz++) {
      const mat = seedAt(sx, sz);
      if (mat !== 0) {
        nearby.push({ x: sx, z: sz, material: mat });
        if (Math.abs(sx - x) <= 1 && Math.abs(sz - z) <= 1) {
          hasImmediateNeighborSeed = true;
        }
      }
    }
  }

  if (!hasImmediateNeighborSeed || nearby.length === 0) {
    return {
      placement: { material: 0, shape: 0, rotation: 0, seed: false, underlayOverride: 0 },
      target: new Array<boolean>(TOPOLOGY_PROBES.length).fill(false),
      lockFullThin: false,
    };
  }

  // 1. Thin authored seeds (single-tile clicks, 1-tile straight roads, 1-tile diagonal paths) stay solid FULL
  if (authoredSeed && isThinSeedTile(x, z, own, seedAt)) {
    // Check if an adjacent representable competing overlay borders this thin seed
    const compWeights = new Map<number, number>();
    const cardinals: readonly [number, number][] = [
      [x - 1, z],
      [x + 1, z],
      [x, z - 1],
      [x, z + 1],
    ];
    for (const [nx, nz] of cardinals) {
      const other = seedAt(nx, nz);
      if (other !== 0 && other !== own && resolveTransitionTarget(other).representable) {
        compWeights.set(other, (compWeights.get(other) ?? 0) + 1);
      }
    }
    if (compWeights.size === 0) {
      return {
        placement: { material: own, shape: OVERLAY_SHAPE_FULL, rotation: 0, seed: true, underlayOverride: 0 },
        target: new Array<boolean>(TOPOLOGY_PROBES.length).fill(true),
        lockFullThin: true,
      };
    }
  }

  // 2. Concave 1-tile diagonal bridge -> crisp Lost-City 45° Diagonal connecting diagonal thin seeds!
  const thinBridge = resolveThinDiagonalBridge(x, z, seedAt);
  if (thinBridge) {
    const fit = fitTopology(thinBridge.target, AUTO_SPILL_COST, false, 16, true, true);
    if (fit.shape !== 0) {
      return {
        placement: {
          material: thinBridge.material,
          shape: fit.shape,
          rotation: fit.rotation,
          seed: false,
          underlayOverride: 0,
        },
        target: thinBridge.target,
        lockFullThin: false,
      };
    }
  }

  // 3. Smooth 5x5 binomial-smoothed vertex contour field per competing material
  const fields = buildTileFields(x, z, nearby, seedAt);
  const probeOwners = TOPOLOGY_PROBES.map((p) => ownerAtProbe(p.u, p.v, fields));

  let material = authoredSeed ? own : ownerAtProbe(0.5, 0.5, fields);
  if (material === 0) {
    const weights = new Map<number, number>();
    for (let i = 0; i < TOPOLOGY_PROBES.length; i++) {
      const m = probeOwners[i]!;
      if (m !== 0) {
        weights.set(m, (weights.get(m) ?? 0) + TOPOLOGY_PROBES[i]!.weight);
      }
    }
    material = pickDominantFromWeights(x, z, weights, nearby);
  }

  if (material === 0) {
    return {
      placement: { material: 0, shape: 0, rotation: 0, seed: false, underlayOverride: 0 },
      target: new Array<boolean>(TOPOLOGY_PROBES.length).fill(false),
      lockFullThin: false,
    };
  }

  // Resolve dominant representable competing material for reversible transition substrate
  const otherWeights = new Map<number, number>();
  for (let i = 0; i < TOPOLOGY_PROBES.length; i++) {
    const owner = probeOwners[i]!;
    if (owner === 0 || owner === material) continue;
    if (!resolveTransitionTarget(owner).representable) continue;
    otherWeights.set(owner, (otherWeights.get(owner) ?? 0) + TOPOLOGY_PROBES[i]!.weight);
  }
  const neighborMaterial = pickDominantFromWeights(x, z, otherWeights, nearby);

  // If this is a thin seed bordering a representable competitor, also include direct cardinal competition
  let effectiveNeighbor = neighborMaterial;
  if (effectiveNeighbor === 0 && authoredSeed) {
    const direct = new Map<number, number>();
    for (const [dx, dz] of [
      [-1, 0],
      [1, 0],
      [0, -1],
      [0, 1],
    ] as const) {
      const o = seedAt(x + dx, z + dz);
      if (o !== 0 && o !== material && resolveTransitionTarget(o).representable) {
        direct.set(o, (direct.get(o) ?? 0) + 1);
      }
    }
    effectiveNeighbor = pickDominantFromWeights(x, z, direct, nearby);
  }

  const target = probeOwners.map((owner) => {
    if (owner === material) return true;
    if (effectiveNeighbor !== 0) {
      return owner !== effectiveNeighbor;
    }
    return owner !== 0;
  });

  // Fit against the 11 authentic Lost-City RS2 shapes (excluding Trapezoid=6), allowing Empty (0) on rounded-off corners
  const fit = fitTopology(target, AUTO_SPILL_COST, false, 16, true, true);

  if (fit.shape === 0) {
    // Rounded-off corner tip cleanly dissolves (thin 1-tile strokes were already preserved above)
    return {
      placement: {
        material: 0,
        shape: 0,
        rotation: 0,
        seed: false,
        underlayOverride: 0,
      },
      target,
      lockFullThin: false,
    };
  }

  const neighborTrans = resolveTransitionTarget(effectiveNeighbor);
  const underlayOverride =
    fit.shape !== OVERLAY_SHAPE_FULL && neighborTrans.representable ? neighborTrans.underlayId : 0;

  return {
    placement: {
      material,
      shape: fit.shape,
      rotation: fit.rotation,
      seed: authoredSeed,
      underlayOverride,
    },
    target,
    lockFullThin: false,
  };
}

function applyPlacementToTile(old: TileData, placement: AutoTilePlacement): TileData {
  let metadata = placement.seed ? TILE_AUTO_SEED : placement.material !== 0 ? TILE_AUTO_GENERATED : 0;
  const authoredUnderlay =
    (old.autoMetadata & TILE_AUTO_UNDERLAY_OVERRIDE) !== 0 ? old.autoBaseUnderlayId : old.underlayId;
  const requestedOverride = placement.underlayOverride;

  let underlay: number;
  let autoBaseUnderlay: number;
  if (requestedOverride !== 0 && requestedOverride !== authoredUnderlay) {
    underlay = requestedOverride;
    autoBaseUnderlay = authoredUnderlay;
    metadata |= TILE_AUTO_UNDERLAY_OVERRIDE;
  } else {
    underlay = authoredUnderlay;
    autoBaseUnderlay = 0;
  }

  return {
    underlayId: underlay,
    overlayId: placement.material,
    overlayShape: placement.shape,
    overlayRotation: placement.rotation,
    autoMetadata: metadata,
    autoBaseUnderlayId: autoBaseUnderlay,
  };
}

/**
 * Lost-City / WorldLab auto-paint for a batch of seed tiles (single click or brush stamp).
 * Passing `materialId = 0` performs an auto-edge erase, cleanly receding neighboring
 * generated fringes and restoring any derived transition substrates.
 */
export function autoPaintOverlaySeeds(
  grid: TerrainGrid,
  seedCoords: readonly { tx: number; tz: number }[],
  materialId: number
): number {
  if (seedCoords.length === 0) return 0;

  const seedOverrides = new Map<string, number>();
  for (const pt of seedCoords) {
    if (!grid.inTileBounds(pt.tx, pt.tz)) continue;
    seedOverrides.set(tileCoordKey(pt.tx, pt.tz), materialId);
  }
  if (seedOverrides.size === 0) return 0;

  // Editable solve zone: stamped tiles + 2-tile smooth-contour radius
  const solveZone = new Set<string>();
  const outerRing = new Set<string>();
  for (const k of seedOverrides.keys()) {
    const [cx, cz] = parseTileCoordKey(k);
    for (let dx = -2; dx <= 2; dx++) {
      for (let dz = -2; dz <= 2; dz++) {
        const tx = cx + dx;
        const tz = cz + dz;
        if (grid.inTileBounds(tx, tz)) solveZone.add(tileCoordKey(tx, tz));
      }
    }
  }
  for (const k of solveZone) {
    const [cx, cz] = parseTileCoordKey(k);
    for (let dx = -1; dx <= 1; dx++) {
      for (let dz = -1; dz <= 1; dz++) {
        const tx = cx + dx;
        const tz = cz + dz;
        if (!grid.inTileBounds(tx, tz)) continue;
        const nk = tileCoordKey(tx, tz);
        if (!solveZone.has(nk)) outerRing.add(nk);
      }
    }
  }

  // Clamp out-of-bounds lookups to the nearest border tile so overlays painted up to the map
  // edge (e.g. rivers, roads) continue cleanly beyond the border instead of rounding off.
  const maxX = grid.width - 1;
  const maxZ = grid.length - 1;
  const seedAt = (sx: number, sz: number): number => {
    const cx = sx < 0 ? 0 : sx > maxX ? maxX : sx;
    const cz = sz < 0 ? 0 : sz > maxZ ? maxZ : sz;
    const key = tileCoordKey(cx, cz);
    if (seedOverrides.has(key)) return seedOverrides.get(key)!;
    const t = grid.getTile(cx, cz);
    return isAutoSeed(t.autoMetadata) ? t.overlayId : 0;
  };

  const placements = new Map<string, AutoTilePlacement>();
  const targets = new Map<string, boolean[]>();
  const starting = new Map<string, ShapeFit>();
  const materials = new Map<string, number>();
  const allowEmptyKeys = new Set<string>();

  for (const k of solveZone) {
    const [tx, tz] = parseTileCoordKey(k);
    const old = grid.getTile(tx, tz);
    const directlyEdited = seedOverrides.has(k);

    if (isManualLocked(old.autoMetadata) && !directlyEdited) {
      if (old.overlayId !== 0 && old.overlayShape >= 1 && old.overlayShape <= 12) {
        starting.set(k, { shape: old.overlayShape, rotation: old.overlayRotation & 3, error: 0 });
        materials.set(k, old.overlayId);
      }
      continue;
    }

    const solved = solveTileFromSeeds(tx, tz, seedAt);
    placements.set(k, solved.placement);
    if (solved.placement.material !== 0 && solved.placement.shape !== 0) {
      targets.set(k, solved.target);
      starting.set(k, { shape: solved.placement.shape, rotation: solved.placement.rotation, error: 0 });
      materials.set(k, solved.placement.material);
      if (!solved.placement.seed) {
        allowEmptyKeys.add(k);
      }
    }
  }

  for (const k of outerRing) {
    const [tx, tz] = parseTileCoordKey(k);
    const old = grid.getTile(tx, tz);
    if (old.overlayId !== 0 && old.overlayShape >= 1 && old.overlayShape <= 12) {
      starting.set(k, { shape: old.overlayShape, rotation: old.overlayRotation & 3, error: 0 });
      materials.set(k, old.overlayId);
    }
  }

  const aligned = harmonizeShapes(targets, starting, materials, AUTO_SPILL_COST, 8, {
    excludeTrapezoid: true,
    allowEmptyKeys,
  });

  for (const [k, fit] of aligned) {
    const oldP = placements.get(k);
    if (!oldP) continue;
    if (oldP.shape === fit.shape && oldP.rotation === fit.rotation) continue;
    if (fit.shape === 0) {
      placements.set(k, {
        material: 0,
        shape: 0,
        rotation: 0,
        seed: oldP.seed,
        underlayOverride: 0,
      });
    } else {
      placements.set(k, {
        material: oldP.material,
        shape: fit.shape,
        rotation: fit.rotation,
        seed: oldP.seed,
        underlayOverride: fit.shape === OVERLAY_SHAPE_FULL ? 0 : oldP.underlayOverride,
      });
    }
  }

  let changed = 0;
  for (const [k, placement] of placements) {
    const [tx, tz] = parseTileCoordKey(k);
    const old = grid.getTile(tx, tz);
    const next = applyPlacementToTile(old, placement);
    if (grid.setTileFull(tx, tz, next)) changed++;
  }
  return changed;
}

/**
 * Manual overlay placement (matches WorldLab TilePaintOperation manual mode):
 * restores authored underlay if a derived substrate was present, writes exact
 * shape + rotation (all 12 RS2 shapes available), and sets MANUAL_LOCK so
 * neighboring auto-paint strokes align to it without overwriting it.
 */
export function paintManualOverlay(
  grid: TerrainGrid,
  tx: number,
  tz: number,
  overlayId: number,
  shape: number,
  rotation: number
): boolean {
  if (!grid.inTileBounds(tx, tz)) return false;
  const old = grid.getTile(tx, tz);
  const authoredUnderlay = grid.getAuthoredUnderlay(tx, tz);
  return grid.setTileFull(tx, tz, {
    underlayId: authoredUnderlay,
    overlayId,
    overlayShape: overlayId === 0 ? 0 : shape,
    overlayRotation: overlayId === 0 ? 0 : rotation & 3,
    autoMetadata: overlayId === 0 ? 0 : lockManualMetadata(old.autoMetadata),
    autoBaseUnderlayId: 0,
  });
}

/**
 * Fits a continuous spatial mask across a region of tiles using the 37-probe
 * Lost-City RS2 shape fitter + overlap-guarded shared-edge harmonizer.
 */
export function fitContinuousMaskToOverlays(
  grid: TerrainGrid,
  materialId: number,
  contains: (worldTileX: number, worldTileZ: number) => boolean,
  options: {
    minTx?: number;
    minTz?: number;
    maxTx?: number;
    maxTz?: number;
    spillCost?: number;
    lockCenter?: boolean;
    preserveExisting?: boolean;
    markAsSeeds?: boolean;
  } = {}
): number {
  const minTx = Math.max(0, options.minTx ?? 0);
  const minTz = Math.max(0, options.minTz ?? 0);
  const maxTx = Math.min(grid.width - 1, options.maxTx ?? grid.width - 1);
  const maxTz = Math.min(grid.length - 1, options.maxTz ?? grid.length - 1);
  const spillCost = options.spillCost ?? AUTO_SPILL_COST;
  const lockCenter = options.lockCenter ?? false;
  const boundaryScale = lockCenter ? 4 : 16;

  const targets = new Map<string, boolean[]>();
  const starting = new Map<string, ShapeFit>();
  const materials = new Map<string, number>();
  const allowEmptyKeys = new Set<string>();
  const centerCovered = new Set<string>();

  for (let tz = minTz; tz <= maxTz; tz++) {
    for (let tx = minTx; tx <= maxTx; tx++) {
      const existing = grid.getTile(tx, tz);
      if (options.preserveExisting && existing.overlayId !== 0 && existing.overlayId !== materialId) {
        continue;
      }
      const target = sampleMaskProbes(tx, tz, contains);
      const fit = fitTopology(target, spillCost, lockCenter, boundaryScale, true, true);
      if (fit.shape === 0) continue;
      const k = tileCoordKey(tx, tz);
      targets.set(k, target);
      starting.set(k, fit);
      materials.set(k, materialId);
      if (contains(tx + 0.5, tz + 0.5)) {
        centerCovered.add(k);
      } else {
        allowEmptyKeys.add(k);
      }
    }
  }

  const aligned = harmonizeShapes(targets, starting, materials, spillCost, 8, {
    excludeTrapezoid: true,
    allowEmptyKeys,
  });

  let changed = 0;
  for (const [k, fit] of aligned) {
    if (fit.shape === 0) continue;
    const [tx, tz] = parseTileCoordKey(k);
    const old = grid.getTile(tx, tz);
    const isSeed = options.markAsSeeds ? centerCovered.has(k) : false;
    const meta = isSeed ? TILE_AUTO_SEED : TILE_AUTO_GENERATED;
    const next: TileData = {
      underlayId: old.underlayId,
      overlayId: materialId,
      overlayShape: fit.shape,
      overlayRotation: fit.rotation,
      autoMetadata: meta,
      autoBaseUnderlayId: old.autoBaseUnderlayId,
    };
    if (grid.setTileFull(tx, tz, next)) changed++;
  }
  return changed;
}

/**
 * Re-solve all auto-generated overlays on the entire map from current AUTO_SEED tiles.
 */
export function resolveAllAutoSeeds(grid: TerrainGrid): number {
  const seeds: { tx: number; tz: number; mat: number }[] = [];
  for (let tz = 0; tz < grid.length; tz++) {
    for (let tx = 0; tx < grid.width; tx++) {
      const t = grid.getTile(tx, tz);
      if (isAutoSeed(t.autoMetadata) && t.overlayId !== 0) {
        seeds.push({ tx, tz, mat: t.overlayId });
      }
    }
  }
  if (seeds.length === 0) return 0;

  // Clamp out-of-bounds lookups to the nearest border tile so border overlays continue beyond the map.
  const maxX = grid.width - 1;
  const maxZ = grid.length - 1;
  const seedAt = (sx: number, sz: number): number => {
    const cx = sx < 0 ? 0 : sx > maxX ? maxX : sx;
    const cz = sz < 0 ? 0 : sz > maxZ ? maxZ : sz;
    const t = grid.getTile(cx, cz);
    return isAutoSeed(t.autoMetadata) ? t.overlayId : 0;
  };

  const placements = new Map<string, AutoTilePlacement>();
  const targets = new Map<string, boolean[]>();
  const starting = new Map<string, ShapeFit>();
  const materials = new Map<string, number>();
  const allowEmptyKeys = new Set<string>();

  for (let tz = 0; tz < grid.length; tz++) {
    for (let tx = 0; tx < grid.width; tx++) {
      const k = tileCoordKey(tx, tz);
      const old = grid.getTile(tx, tz);
      if (isManualLocked(old.autoMetadata)) {
        if (old.overlayId !== 0 && old.overlayShape >= 1 && old.overlayShape <= 12) {
          starting.set(k, { shape: old.overlayShape, rotation: old.overlayRotation & 3, error: 0 });
          materials.set(k, old.overlayId);
        }
        continue;
      }
      const solved = solveTileFromSeeds(tx, tz, seedAt);
      placements.set(k, solved.placement);
      if (solved.placement.material !== 0 && solved.placement.shape !== 0) {
        targets.set(k, solved.target);
        starting.set(k, { shape: solved.placement.shape, rotation: solved.placement.rotation, error: 0 });
        materials.set(k, solved.placement.material);
        if (!solved.placement.seed) {
          allowEmptyKeys.add(k);
        }
      }
    }
  }

  const aligned = harmonizeShapes(targets, starting, materials, AUTO_SPILL_COST, 8, {
    excludeTrapezoid: true,
    allowEmptyKeys,
  });

  for (const [k, fit] of aligned) {
    const oldP = placements.get(k);
    if (!oldP) continue;
    if (fit.shape === 0) {
      placements.set(k, {
        material: 0,
        shape: 0,
        rotation: 0,
        seed: oldP.seed,
        underlayOverride: 0,
      });
    } else {
      placements.set(k, {
        material: oldP.material,
        shape: fit.shape,
        rotation: fit.rotation,
        seed: oldP.seed,
        underlayOverride: fit.shape === OVERLAY_SHAPE_FULL ? 0 : oldP.underlayOverride,
      });
    }
  }

  let changed = 0;
  for (const [k, p] of placements) {
    const [tx, tz] = parseTileCoordKey(k);
    const old = grid.getTile(tx, tz);
    if (grid.setTileFull(tx, tz, applyPlacementToTile(old, p))) changed++;
  }
  return changed;
}
